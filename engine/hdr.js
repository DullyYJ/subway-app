function hdrCat(h) {
  if (h >= 7 && h < 10) return 'morning';
  if (h >= 10 && h < 15) return 'noon';
  if (h >= 15 && h < 18) return 'afternoon';
  if (h >= 18 && h < 20) return 'evening';
  return 'night';
}
function hdrStripEmoji(t) {
  if (t == null) return '';
  return String(t)
    .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}\u{FE00}-\u{FE0F}\u{200D}\u{20E3}\u{E0020}-\u{E007F}\u{1F1E6}-\u{1F1FF}]/gu, '')
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}
function hdrScreen(inp) {
  inp = inp || {};
  var nowMs = Number(inp.nowMs); if (!isFinite(nowMs) || nowMs <= 0) nowMs = Date.now();
  var tz = Number(inp.tzOffsetMin); if (!isFinite(tz) || Math.abs(tz) > 840) tz = 540;
  var d = new Date(nowMs + tz * 60000), h = d.getUTCHours(), day = d.getUTCDate();
  var cat = hdrCat(h), arr = (HDR_MSGS[cat] || HDR_MSGS.morning).slice();
  var seed = day * 31 + h + 7;                                 // 날짜 · 시각 씨앗 섞기(웹 _refreshMarqueeList 와 같다)
  for (var i = arr.length - 1; i > 0; i--) {
    seed = (seed * 9301 + 49297) % 233280;
    var j = Math.floor(seed / 233280 * (i + 1)), t = arr[i]; arr[i] = arr[j]; arr[j] = t;
  }
  var msgs = [];
  for (var k = 0; k < arr.length && msgs.length < 60; k++) { var s = hdrStripEmoji(arr[k]); if (s) msgs.push(s.length > 80 ? s.slice(0, 80) : s); }
  return { ok: true, v: 1, screen: 'hdr', rev: cat + ':' + day + ':' + h, cover: 'tab', head: [],
    body: [{ t: 'marq', h: 26, pad: [8, 14, 8, 14], msgs: msgs, pass: 16000, grad: 6000, line: true }], info: { cat: cat, hour: h, n: msgs.length } };
}
